/// Returns articles matching a specific pregnancy week dynamically.
List<Article> getArticlesForPregnancyWeek(int week) {
  final targetWeek = week.clamp(1, 40);

  // 1. Look for week-range specific articles
  final weekSpecific = allMomBeeArticles.where((a) {
    if (a.journeyTag != 'pregnant') return false;
    if (a.startWeek != null && a.endWeek != null) {
      return targetWeek >= a.startWeek! && targetWeek <= a.endWeek!;
    }
    return false;
  }).toList();

  if (weekSpecific.isNotEmpty) return weekSpecific;

  // 2. Fallback to trimester articles
  int targetTrimester = 1;
  if (targetWeek >= 14 && targetWeek <= 27) targetTrimester = 2;
  if (targetWeek >= 28) targetTrimester = 3;

  return allMomBeeArticles
      .where((a) => a.journeyTag == 'pregnant' && a.trimester == targetTrimester)
      .toList();
}

/// Helper function for Context-Aware Articles across journeys:
List<Article> getArticlesForJourney(
  JourneyType journey, {
  int? pregnancyWeek,
  String? babyStageId,
}) {
  switch (journey) {
    case JourneyType.planning:
      return allMomBeeArticles
          .where((a) => a.journeyTag == 'planning')
          .toList();
    case JourneyType.pregnant:
      final week = pregnancyWeek ?? 1;
      return getArticlesForPregnancyWeek(week);
    case JourneyType.baby:
      final stage = babyStageId ?? 'newborn';
      final stageArticles = allMomBeeArticles
          .where((a) => a.journeyTag == 'baby' && a.babyStageId == stage)
          .toList();
      if (stageArticles.isNotEmpty) return stageArticles;
      return allMomBeeArticles.where((a) => a.journeyTag == 'baby').toList();
    case JourneyType.general:
      return allMomBeeArticles
          .where((a) => a.journeyTag == 'general')
          .toList();
  }
}

